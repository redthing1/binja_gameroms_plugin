def nds_mmio_registers() -> list[MmioRegister]:
    regs: list[MmioRegister] = []
    for addr, name, desc in NDS_MMIO_REGISTERS_RAW:
        width = WIDTH_OVERRIDES.get(name, DEFAULT_MMIO_WIDTH)
        regs.append(MmioRegister(addr=addr, name=name, width=width, description=desc))
    return regs
