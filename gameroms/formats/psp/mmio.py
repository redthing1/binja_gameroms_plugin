def psp_mmio_registers() -> list[MmioRegister]:
    regs: list[MmioRegister] = []
    for addr, name, desc in PSP_MMIO_REGISTERS_RAW:
        regs.append(
            MmioRegister(
                addr=addr, name=name, width=DEFAULT_MMIO_WIDTH, description=desc
            )
        )
    return regs
